import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {atomicJson,command} from './orca-adapter.mjs';
const scripts=path.dirname(fileURLToPath(import.meta.url)),cwd=path.resolve(process.env.POS_TEST_CWD || "tests/pi-bots-orca");
const dir=path.join(cwd,'chat-ui'),session=path.join(dir,'exact-session.jsonl'),runId='chat-ui-test';
fs.mkdirSync(dir,{recursive:true});
const messages=[{type:'session',id:'ui-session'}];
for(let i=0;i<650;i++)messages.push({type:'message',id:'message-'+i,message:{role:i%2?'assistant':'user',content:[{type:'text',text:i===0?'ORIGINAL-FIRST-TASK':'Message '+i+' '+ 'x'.repeat(520)}]}});
fs.writeFileSync(session,messages.map(x=>JSON.stringify(x)).join('\n')+'\n');
const status={runId,cwd,state:'running',steps:[{agent:'scout',status:'running',sessionFile:session}]};atomicJson(path.join(dir,'status.json'),status);
const ps=path.join(process.env.SystemRoot,'System32/WindowsPowerShell/v1.0/powershell.exe');
const records=path.join(dir,'records');
const publication=await command(ps,['-NoLogo','-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(scripts,'Publish-PiBotView.ps1'),'-RunId',runId,'-AsyncDir',dir,'-ChildIndex','0','-Title','Pi Bots complete chat test','-NoHerdr','-RecordRoot',records]);
assert(publication.ok,JSON.stringify(publication));const view=publication.data.view.orca;
assert.equal(view.status,'created');
const exe=path.join(process.env.LOCALAPPDATA,'Programs/orca/resources/bin/orca.exe');
const read=()=>command(exe,['terminal','read','--terminal',view.handle,'--json']);
await new Promise(r=>setTimeout(r,2000));const lastPage=await read();
await command(exe,['terminal','send','--terminal',view.handle,'--text','\x1b[H','--json']);
await new Promise(r=>setTimeout(r,1000));const firstPage=await read();
assert(JSON.stringify(firstPage).includes('ORIGINAL-FIRST-TASK'),'Home navigates to original task beyond old 256KB cap');
fs.appendFileSync(session,JSON.stringify({type:'message',id:'late',message:{role:'assistant',content:[{type:'text',text:'NEW-LIVE-FINAL-MESSAGE'}]}})+'\n');
await new Promise(r=>setTimeout(r,1000));const anchored=await read();
assert(JSON.stringify(anchored).includes('ORIGINAL-FIRST-TASK'),'New message keeps historical page visible');
await command(exe,['terminal','send','--terminal',view.handle,'--text','f','--json']);
await new Promise(r=>setTimeout(r,1000));const followed=await read();
assert(JSON.stringify(followed).includes('NEW-LIVE-FINAL-MESSAGE'),'Follow displays newly persisted message');
atomicJson(path.join(dir,'ui-test-result.json'),{publication:publication.data,lastPage:lastPage.data,firstPage:firstPage.data,anchored:anchored.data,followed:followed.data});
status.state='complete';status.steps[0].status='completed';atomicJson(path.join(dir,'status.json'),status);
const cleanup=await command(ps,['-NoLogo','-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(scripts,'Close-PiBotViews.ps1'),'-RunId',runId,'-RecordRoot',records]);assert(cleanup.ok);
console.log('PASS: real Orca chat tab; Home reaches first task beyond 256KB; new messages preserve scroll; follow reaches live output; exact owned tab cleanup');
