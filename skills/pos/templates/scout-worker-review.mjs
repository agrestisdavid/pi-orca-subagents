// POS reference workflow: Scout -> Worker -> fresh structured review -> optional fix rounds.
//
// Run it through the native engine (no wrapper control plane), for example:
//   pi_bots({ action: "start", execution: "orca-tui", coordination: "orca",
//             viewMode: "orca",
//             launch: { workflowScriptPath: "<absolute path to this file>", cwd: "<workspace>" } })
//   subagent({ workflowScriptPath: "<absolute path to this file>" })
//
// Contract rules implemented here (see skills/pos/SKILL.md, "Output contracts"):
// - A review that is delivered successfully stays a successful execution, even
//   when its verdict is "changes_required". The verdict is a domain judgment,
//   not an execution error. Only ok === false is an infrastructure failure.
// - The reviewer is asked for the structured result only. A Markdown report is
//   generated by the parent from the structured result afterwards, never by
//   the reviewer. structured_output ends the child's turn; every mandatory
//   artifact must exist before that call.
// - Optional result fields are omitted or JSON-compatible; a missing optional
//   field must not abort the workflow.
// - Finished successful results are reused through run references when
//   provided. A configured reuse reference is NOT an authorization to start
//   a replacement run: when the referenced run is still active, failed,
//   unknown, or the reference cannot be resolved (including status transport
//   errors), the workflow stops visibly with status 'reuse_blocked',
//   preserving the reference and the observed state. No replacement run and
//   no dependent step is started. Only "State: complete" without error
//   markers is reusable.
// - Infrastructure errors stop dependent steps: no review after a failed
//   scout/worker, no fix round after a failed review/fix.
// - Exactly one writer per workspace: the fix rounds run serially in the same
//   workspace, each after the previous child has settled. Reviews are fresh.

// ---------------------------------------------------------------------------
// Configuration block: adjust these per task. Profiles are agent names chosen
// from the available agents - never model names.
// ---------------------------------------------------------------------------
const CONFIG = {
	// Absolute workspace path; the single writer boundary for this workflow.
	cwd: "",
	// Agent profiles (installed native profiles, not model names).
	scoutAgent: "scout",
	writerAgent: "writer",
	reviewerAgent: "reviewer",
	// Bounded task texts.
	scoutTask:
		"Inspect the assigned workspace and report the relevant context, constraints, and the files the implementation must touch. Read-only.",
	implementationTask:
		"Implement the bounded task in this workspace. Keep one writer (you), run the focused validation that can fail for your change, and report the result with evidence.",
	// The reviewer gets a fresh read-only context and returns the structured
	// result only. No Markdown report file is required from the reviewer.
	reviewTask:
		"Fresh read-only review of the current workspace state. Judge correctness against the task, cite concrete evidence for every finding, and distinguish blockers from non-blockers. " +
		"Output contract: call structured_output exactly once and last - it ends your turn; create every mandatory artifact before that call. " +
		"Your verdict is a domain judgment: 'changes_required' is a successful, well-formed review, not an execution failure. " +
		"Do not write report files and do not modify the workspace.",
	// Maximum number of fresh review rounds (1..3).
	maxReviewRounds: 3,
	// Optional reuse references to finished runs (run id or workflow receipt).
	// A reference is only honored when its status reports a finished
	// successful run; anything else stops the workflow visibly (see the
	// header contract). Never treated as permission for a replacement run.
	reuse: {
		scoutRunId: undefined,
		implementationRunId: undefined,
	},
	// Optional artifacts the delivery contract requires in the workspace after
	// the workflow. The sandbox has no filesystem access, so existence is
	// verified by the parent. The machine-readable outputContract block below
	// (carried in every terminal result that contains a structured review)
	// states the contract and the exact report string the parent must use when
	// a required artifact is missing:
	// "Output contract not fulfilled; structured result exists."
	// The child execution itself remains successful.
	requiredArtifacts: [],
};

const REVIEW_SCHEMA = {
	type: "object",
	additionalProperties: false,
	required: ["verdict", "findings", "checked"],
	properties: {
		verdict: { type: "string", enum: ["approved", "changes_required"] },
		findings: {
			type: "array",
			items: {
				type: "object",
				additionalProperties: false,
				required: ["severity", "title", "detail"],
				properties: {
					severity: { type: "string", enum: ["blocker", "non_blocker"] },
					title: { type: "string" },
					detail: { type: "string" },
					// Optional, JSON-compatible: evidence citation.
					evidence: { type: "string" },
				},
			},
		},
		checked: { type: "array", items: { type: "string" } },
	},
};

const warnings = [];
const reused = [];

// The sandbox only accepts plain JSON run params; empty configuration slots
// (cwd, tasks) are omitted instead of being passed through.
const pick = (params) => {
	const out = {};
	for (const [key, value] of Object.entries(params)) {
		if (value === undefined || (typeof value === "string" && value.trim() === "")) continue;
		out[key] = value;
	}
	return out;
};

// A failing child rejects the run promise in the sandbox. Convert that into
// the same failed-result shape so dependent steps stop with a visible note
// instead of an unstructured workflow crash.
const runChild = (key, params) =>
	runs.run(key, params).then(
		(result) => result,
		(error) => ({ ok: false, error: String((error && error.message) || error) }),
	);

// The status action reports "State: <state>" with state in
// queued/running/complete/failed/partial/paused/stopped/rejected. A reuse
// reference is honored only for a finished successful run: ok without any
// error/detached/stopped/interrupted marker AND "State: complete". An
// active run (running/queued/detached), a failed or otherwise incomplete
// state, an unresolvable reference, and status transport errors all yield a
// blocked outcome - a configured reference never authorizes a replacement
// run, and dependent steps must not start on unverified results.
const reuseStateOf = (output) => {
	for (const line of String(output || "").split("\n")) {
		if (line.startsWith("State: ")) return line.slice("State: ".length).trim();
	}
	return undefined;
};
const isFinishedSuccessful = (result) =>
	!!result &&
	result.ok === true &&
	result.error === undefined &&
	result.detached !== true &&
	result.stopped !== true &&
	result.interrupted !== true &&
	reuseStateOf(result.output) === "complete";
const resolveReuseReference = (reference, label) =>
	runs.status(reference).then(
		(result) => ({ reference, label, result: result || { ok: false, output: "status returned no result" } }),
		(error) => ({ reference, label, result: { ok: false, output: "status transport error: " + String((error && error.message) || error) } }),
	);
const reuseBlockResult = (outcome) => ({
	status: "reuse_blocked",
	failedStep: outcome.label.toLowerCase() + "-reuse",
	reference: outcome.reference,
	observedState: reuseStateOf(outcome.result.output),
	error: outcome.result.ok === true ? undefined : outcome.result.error || outcome.result.output || "status unavailable",
	warnings,
	requiredArtifacts: CONFIG.requiredArtifacts,
	note:
		"The configured reuse reference '" + outcome.reference + "' did not resolve to a finished, successful run" +
		(reuseStateOf(outcome.result.output) ? " (observed state: " + reuseStateOf(outcome.result.output) + ")" : "") +
		". Stopped visibly: no replacement run was started and no dependent step was run. " +
		"The reference is preserved for inspection; re-run with a corrected reference or without the reuse setting.",
});

const compactReview = (entry) => ({
	round: entry.round,
	verdict: entry.verdict,
	blockers: entry.findings.filter((finding) => finding.severity === "blocker").length,
	nonBlockers: entry.findings.filter((finding) => finding.severity !== "blocker").length,
});

const buildFixTask = (structured) => {
	const lines = [
		"The fresh read-only review delivered its structured result with verdict 'changes_required'. " +
			"That is a domain judgment, not an execution failure: fix the findings below in this workspace, " +
			"then re-run the focused validation that can fail for the change. You are the only writer for this workspace in this round.",
		"",
	];
	for (const finding of structured.findings || []) {
		lines.push("- [" + finding.severity + "] " + finding.title + ": " + finding.detail + (finding.evidence ? " (evidence: " + finding.evidence + ")" : ""));
	}
	lines.push("", "Keep the existing review contract: no report files, no scope creep beyond the findings.");
	return lines.join("\n");
};

// --- Scout (or reuse of a finished scout run) -------------------------------
let scout;
if (CONFIG.reuse.scoutRunId) {
	const existing = await resolveReuseReference(CONFIG.reuse.scoutRunId, "Scout");
	if (isFinishedSuccessful(existing.result)) {
		scout = existing.result;
		reused.push("scout:" + CONFIG.reuse.scoutRunId);
	} else {
		return reuseBlockResult(existing);
	}
} else {
	scout = await runChild("scout", pick({ agent: CONFIG.scoutAgent, task: CONFIG.scoutTask, context: "fresh", cwd: CONFIG.cwd }));
}
if (!scout.ok) {
	return {
		status: "infrastructure_error",
		failedStep: "scout",
		error: scout.error || "scout child failed",
		warnings,
		requiredArtifacts: CONFIG.requiredArtifacts,
		note: "Infrastructure error: the dependent steps (implementation, review) were not started. Existing results are unchanged.",
	};
}

// --- Implementation: exactly one writer for the workspace ------------------
let implementation;
if (CONFIG.reuse.implementationRunId) {
	const existing = await resolveReuseReference(CONFIG.reuse.implementationRunId, "Implementation");
	if (isFinishedSuccessful(existing.result)) {
		implementation = existing.result;
		reused.push("implementation:" + CONFIG.reuse.implementationRunId);
	} else {
		return reuseBlockResult(existing);
	}
} else {
	implementation = await runChild("implement", pick({ agent: CONFIG.writerAgent, task: CONFIG.implementationTask, context: "fresh", cwd: CONFIG.cwd }));
}
if (!implementation.ok) {
	return {
		status: "infrastructure_error",
		failedStep: "implementation",
		error: implementation.error || "implementation child failed",
		scout: runs.ref(scout),
		warnings,
		requiredArtifacts: CONFIG.requiredArtifacts,
		note: "Infrastructure error: the review loop was not started. Existing results are unchanged.",
	};
}

// Machine-readable output contract for terminal results that contain a
// structured review: the structured result exists, and the parent must
// verify every required artifact in the workspace and, on a missing file,
// report the exact string below. This block is the executable carrier of
// the contract in the workflow result (delivered to the parent and previewed
// by the run status surface); it replaces a note-only instruction.
const outputContract = {
	structuredResult: "exists",
	requiredArtifacts: CONFIG.requiredArtifacts,
	missingArtifactReport: "Output contract not fulfilled; structured result exists.",
	verification: "parent",
};

// --- Fresh structured review loop (at most CONFIG.maxReviewRounds) ---------
const reviews = [];
let lastReview = undefined;
for (let round = 1; round <= CONFIG.maxReviewRounds; round++) {
	const review = await runChild("review-" + round, pick({
		agent: CONFIG.reviewerAgent,
		task: CONFIG.reviewTask,
		context: "fresh",
		cwd: CONFIG.cwd,
		outputSchema: REVIEW_SCHEMA,
	}));
	if (!review.ok) {
		return {
			status: "infrastructure_error",
			failedStep: "review-" + round,
			error: review.error || "review child failed",
			scout: runs.ref(scout),
			implementation: runs.ref(implementation),
			reviews: reviews.map(compactReview),
			warnings,
			requiredArtifacts: CONFIG.requiredArtifacts,
			note: "Infrastructure error in review round " + round + ": no fix round was started. Independent results are unchanged.",
		};
	}
	// The structured result is the contract. A missing optional field must not
	// abort the workflow; only the verdict drives the loop.
	const structured = review.structuredOutput && typeof review.structuredOutput === "object" ? review.structuredOutput : {};
	const findings = Array.isArray(structured.findings) ? structured.findings : [];
	lastReview = { round, verdict: structured.verdict === "approved" ? "approved" : "changes_required", findings };
	reviews.push(lastReview);
	emit("review round " + round + ": " + lastReview.verdict + " (" + findings.length + " findings)");
	if (lastReview.verdict === "approved") {
		return {
			status: "complete",
			verdict: "approved",
			rounds: round,
			reviews: reviews.map(compactReview),
			scout: runs.ref(scout),
			implementation: runs.ref(implementation),
			review: runs.ref(review),
			reused,
			warnings,
			requiredArtifacts: CONFIG.requiredArtifacts,
			outputContract,
			note: "Review completed - no changes required. The parent may generate any requested Markdown report from the structured result (see the run references). Verify the outputContract.requiredArtifacts in the workspace before declaring delivery complete.",
		};
	}
	if (round >= CONFIG.maxReviewRounds) {
		return {
			status: "changes_required_after_limit",
			verdict: "changes_required",
			rounds: round,
			reviews: reviews.map(compactReview),
			lastFindings: findings,
			scout: runs.ref(scout),
			implementation: runs.ref(implementation),
			review: runs.ref(review),
			reused,
			warnings,
			requiredArtifacts: CONFIG.requiredArtifacts,
			outputContract,
			note: "Review completed - changes required (round limit " + CONFIG.maxReviewRounds + " reached). The last structured review is the decision basis.",
		};
	}
	const fix = await runChild("fix-" + round, pick({ agent: CONFIG.writerAgent, task: buildFixTask(lastReview), context: "fresh", cwd: CONFIG.cwd }));
	if (!fix.ok) {
		return {
			status: "infrastructure_error",
			failedStep: "fix-" + round,
			error: fix.error || "fix child failed",
			scout: runs.ref(scout),
			implementation: runs.ref(implementation),
			reviews: reviews.map(compactReview),
			warnings,
			requiredArtifacts: CONFIG.requiredArtifacts,
			note: "Infrastructure error in fix round " + round + ": no further review was started. Independent results are unchanged.",
		};
	}
	implementation = fix;
}
return {
	status: "changes_required_after_limit",
	verdict: lastReview ? lastReview.verdict : "unknown",
	rounds: reviews.length,
	reviews: reviews.map(compactReview),
	scout: runs.ref(scout),
	implementation: runs.ref(implementation),
	reused,
	warnings,
	requiredArtifacts: CONFIG.requiredArtifacts,
	note: "Review loop finished; see the last structured review for the decision basis.",
};
